#!/bin/bash
# Portcullis: DokuWiki start-up configuration. compose.yml installs this file
# into /custom-cont-init.d, so the linuxserver image runs it (as root) at
# every start, after its own setup and before nginx/php-fpm start.
# Everything is derived from the instance's environment and re-applied on
# each start: a hostname, client or group change needs no action inside
# DokuWiki. Never print DOKUWIKI_OIDC_SECRET.
set -euo pipefail

: "${PORTCULLIS_DOMAIN:?}" "${PORTCULLIS_HOST_DOKUWIKI:?}" "${PORTCULLIS_OIDC_CLIENT_ID:?}"
: "${PORTCULLIS_ACCESS_GROUP:?}" "${PORTCULLIS_ADMIN_GROUP:?}" "${PORTCULLIS_TRAEFIK_IP:?}"
: "${DOKUWIKI_OIDC_SECRET:?}"
for g in "$PORTCULLIS_ACCESS_GROUP" "$PORTCULLIS_ADMIN_GROUP"; do
  case "$g" in
    ""|*[!a-z0-9_-]*) echo "portcullis: unexpected group name '$g'" >&2; exit 1 ;;
  esac
done

DW=/config/dokuwiki
PLUGINS=$DW/lib/plugins
CONF=$DW/conf
PHP=$(command -v php || command -v php85)

# ── OAuth plugins, pinned (maintained by CosmoCode, the DokuWiki authors) ──
# https://www.dokuwiki.org/plugin:oauth, https://www.dokuwiki.org/plugin:oauthgeneric
# Upgrade: bump date + sha256 together (GitHub tag archives of
# cosmocode/dokuwiki-plugin-oauth and cosmocode/dokuwiki-plugin-oauthgeneric).
install_plugin() {
  local name=$1 repo=$2 tag=$3 sha=$4 tmp
  if grep -qx "date *$tag" "$PLUGINS/$name/plugin.info.txt" 2>/dev/null; then
    return 0
  fi
  echo "portcullis: installing DokuWiki plugin $name $tag"
  tmp=$(mktemp -d)
  curl -fsSL "https://github.com/$repo/archive/refs/tags/$tag.tar.gz" -o "$tmp/plugin.tar.gz"
  echo "$sha  $tmp/plugin.tar.gz" | sha256sum -c - >/dev/null
  mkdir "$tmp/x"
  tar -xzf "$tmp/plugin.tar.gz" -C "$tmp/x"
  rm -rf "${PLUGINS:?}/$name"
  mv "$tmp/x/"*/ "$PLUGINS/$name"
  rm -rf "$tmp"
}
install_plugin oauth cosmocode/dokuwiki-plugin-oauth 2026-10-29 \
  12ce0ff222be76ed1dc3a2089a265d012b7c90ec610086c5cc94d1f0f4a9cee0
install_plugin oauthgeneric cosmocode/dokuwiki-plugin-oauthgeneric 2025-10-02 \
  b55eb7d9226fb3a0d35c51bb677cc32e5cb51db17f973aaaf2413b0f8a3da3b5

# authplain (which the oauth backend extends) needs the user file.
if [ ! -f "$CONF/users.auth.php" ]; then
  cp "$CONF/users.auth.php.dist" "$CONF/users.auth.php" 2>/dev/null \
    || printf '# users.auth.php\n# <?php exit()?>\n' > "$CONF/users.auth.php"
fi

# ── Settings: local.protected.php wins over local.php and the admin UI ──
"$PHP" -r '
$e = static fn (string $k): string => (string) getenv($k);
$realm = "https://auth." . $e("PORTCULLIS_DOMAIN") . "/realms/portcullis/protocol/openid-connect";
$conf = [
  // Hostname of this instance (re-applied at every start).
  "baseurl" => "https://" . $e("PORTCULLIS_HOST_DOKUWIKI"),
  "basedir" => "/",
  "trustedproxies" => [$e("PORTCULLIS_TRAEFIK_IP")],
  "useacl" => 1,
  "authtype" => "oauth",
  "superuser" => "@" . $e("PORTCULLIS_ADMIN_GROUP"),
  // No local registration or password reset, and no profile edits: the
  // account key (see json-mail) must not be changeable by its user.
  "disableactions" => "register,resendpwd,profile,profile_delete",
];
$oauth = [
  // Only the Portcullis button, no password form (break-glass: see notes).
  "singleService" => 1,
  "register-on-auth" => 1,
  // Groups follow the groups claim at each login.
  "overwrite-groups" => 1,
  "mailRestriction" => "",
];
$generic = [
  "key" => $e("PORTCULLIS_OIDC_CLIENT_ID"),
  "secret" => $e("DOKUWIKI_OIDC_SECRET"),
  "authurl" => "$realm/auth",
  "tokenurl" => "$realm/token",
  "userurl" => "$realm/userinfo",
  "logouturl" => "",
  "authmethod" => 1,
  "scopes" => ["openid", "profile"],
  "needs-state" => 1,
  "json-user" => "preferred_username",
  "json-name" => "name",
  // The oauth plugin finds accounts BY EMAIL. LLDAP emails are
  // user-editable, so the "mail" it keys on is the immutable username.
  "json-mail" => "preferred_username",
  "json-grps" => "groups",
  "label" => "Portcullis",
];
$out = "<?php\n// Generated by the Portcullis template at every start; edits are lost.\n";
foreach ($conf as $k => $v) $out .= "\$conf[" . var_export($k, true) . "] = " . var_export($v, true) . ";\n";
foreach (["oauth" => $oauth, "oauthgeneric" => $generic] as $p => $vals)
  foreach ($vals as $k => $v)
    $out .= "\$conf[\"plugin\"][" . var_export($p, true) . "][" . var_export($k, true) . "] = " . var_export($v, true) . ";\n";
file_put_contents($argv[1] . ".new", $out);
rename($argv[1] . ".new", $argv[1]);
' "$CONF/local.protected.php"
chmod 0640 "$CONF/local.protected.php"

# ── ACL: no anonymous access, the access group reads and edits ──
# Rules for @ALL, @user (every account) and @generic (every OAuth account)
# are replaced; all other rules are kept. Admins are superusers.
"$PHP" -r '
$file = $argv[1];
$keep = [];
foreach (is_file($file) ? file($file, FILE_IGNORE_NEW_LINES) : [] as $line) {
  $f = preg_split("/\s+/", trim(preg_replace("/#.*$/", "", $line)));
  if (count($f) >= 3 && in_array($f[1], ["@ALL", "@user", "@generic"], true)) continue;
  if (strpos($line, "# Portcullis") !== false) continue;
  $keep[] = $line;
}
if (!$keep) $keep = ["# acl.auth.php", "# <?php exit()?>"];
$keep[] = "*\t@ALL\t0\t# Portcullis (managed, re-applied at every start)";
$keep[] = "*\t@" . rawurlencode(getenv("PORTCULLIS_ACCESS_GROUP")) . "\t8\t# Portcullis (managed, re-applied at every start)";
file_put_contents($file . ".new", implode("\n", $keep) . "\n");
rename($file . ".new", $file);
' "$CONF/acl.auth.php"

# The setup wizard is not needed (this script writes the configuration) and
# must never be reachable without the gateway.
rm -f /app/www/public/install.php

lsiown -R abc:abc "$PLUGINS/oauth" "$PLUGINS/oauthgeneric"
lsiown abc:abc "$CONF/local.protected.php" "$CONF/acl.auth.php" "$CONF/users.auth.php"
echo "portcullis: DokuWiki configured for https://$PORTCULLIS_HOST_DOKUWIKI (OIDC client $PORTCULLIS_OIDC_CLIENT_ID)"
